#include <iostream>
using namespace std;
#include <bits/stdc++.h>
int n,k;
int grid[21][21];
int dist[5][21][21];
int dx[4] = {-1,1,0,0};
int dy[4] = {0,0,-1,1};
void bfs(int id,int sx,int sy){
    for(int i = 0;i < n;i++){
        for(int j = 0;j < n;j++){
            dist[id][i][j] = -1;
        }
    }
    queue<pair<int,int>> q;
    q.push({sx,sy});
    dist[id][sx][sy] = 0;
    while(!q.empty()){
        auto temp = q.front();
        int x = temp.first;
        int y = temp.second;
        q.pop();
        for(int i = 0;i < 4;i++){
            int nx = x + dx[i];
            int ny = y + dy[i];
            if(nx >= 0 && nx < n && ny >= 0 && ny < n && grid[nx][ny] == 1 && dist[id][nx][ny] == -1){
                dist[id][nx][ny] = dist[id][x][y] + 1;
                q.push({nx,ny});
            }
        }
    }
}
